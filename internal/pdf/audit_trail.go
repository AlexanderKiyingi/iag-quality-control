package pdf

import (
	"bytes"
	"encoding/json"
	"fmt"
	"sort"
	"strings"
	"time"

	"github.com/jung-kurt/gofpdf"
)

// AuditEntry is one change-log row as the audit-trail PDF prints it.
type AuditEntry struct {
	When    time.Time
	Entity  string
	Record  string
	Op      string
	Actor   string
	Reason  string
	Changes map[string]any
}

// AuditTrailData is a filtered slice of the change log (017) for an auditor.
type AuditTrailData struct {
	Filters     []string
	GeneratedBy string
	GeneratedAt time.Time
	Entries     []AuditEntry
	Truncated   bool
}

func auditValue(v any) string {
	switch t := v.(type) {
	case nil:
		return "∅"
	case string:
		if t == "" {
			return `""`
		}
		return t
	default:
		b, _ := json.Marshal(t)
		return string(b)
	}
}

func clip(s string, n int) string {
	r := []rune(s)
	if len(r) <= n {
		return s
	}
	return string(r[:n-1]) + "…"
}

/*
RenderAuditTrail prints who changed what, when and why — every entry with
its before → after values — so a reviewer can work from paper. Long values are
clipped; the API holds them whole.
*/
func RenderAuditTrail(d AuditTrailData) ([]byte, error) {
	var buf bytes.Buffer
	return writePDF(&buf, func(pdf *gofpdf.Fpdf) {
		pdf.SetFooterFunc(func() {
			pdf.SetY(-12)
			pdf.SetFont("Arial", "I", 8)
			pdf.CellFormat(0, 8, tr(pdf, fmt.Sprintf("IAG Quality Control — audit trail — page %d", pdf.PageNo())), "", 0, "C", false, 0, "")
		})
		heading(pdf, "AUDIT TRAIL")
		line(pdf, "Generated:", d.GeneratedAt.UTC().Format("2006-01-02 15:04 UTC"))
		if d.GeneratedBy != "" {
			line(pdf, "Generated by:", d.GeneratedBy)
		}
		filters := "all records"
		if len(d.Filters) > 0 {
			filters = strings.Join(d.Filters, "; ")
		}
		line(pdf, "Filters:", filters)
		count := fmt.Sprintf("%d", len(d.Entries))
		if d.Truncated {
			count += " (limit reached — narrow the filters for the rest)"
		}
		line(pdf, "Entries:", count)
		pdf.Ln(3)
		if len(d.Entries) == 0 {
			pdf.SetFont("Arial", "", 10)
			pdf.Cell(0, 6, tr(pdf, "No changes match these filters."))
			return
		}
		for _, e := range d.Entries {
			if pdf.GetY() > 260 {
				pdf.AddPage()
			}
			pdf.SetDrawColor(220, 220, 220)
			pdf.Line(18, pdf.GetY(), 192, pdf.GetY())
			pdf.Ln(1.5)
			pdf.SetFont("Arial", "B", 9.5)
			actor := e.Actor
			if actor == "" {
				actor = "system"
			}
			pdf.MultiCell(0, 5, tr(pdf, fmt.Sprintf("%s  ·  %s %s  ·  %s  ·  %s",
				e.When.UTC().Format("2006-01-02 15:04:05"), e.Entity, e.Record, e.Op, actor)), "", "L", false)
			pdf.SetFont("Arial", "", 9)
			if e.Reason != "" {
				pdf.MultiCell(0, 4.5, tr(pdf, "Reason: "+e.Reason), "", "L", false)
			}
			keys := make([]string, 0, len(e.Changes))
			for k := range e.Changes {
				keys = append(keys, k)
			}
			sort.Strings(keys)
			for _, k := range keys {
				v := e.Changes[k]
				text := ""
				if m, ok := v.(map[string]any); ok && e.Op == "UPDATE" {
					text = fmt.Sprintf("%s: %s → %s", k, clip(auditValue(m["old"]), 120), clip(auditValue(m["new"]), 120))
				} else {
					text = fmt.Sprintf("%s: %s", k, clip(auditValue(v), 160))
				}
				pdf.SetX(24)
				pdf.MultiCell(0, 4.2, tr(pdf, text), "", "L", false)
			}
			pdf.Ln(1.5)
		}
	})
}
