package pdf

import (
	"bytes"
	"strings"

	"github.com/jung-kurt/gofpdf"
)

type CoAData struct {
	CoaNumber       string
	LotBusinessID   string
	BatchBusinessID string
	DocumentRef     string
	IssuedBy        string
	IssuedAt        string
	Status          string
	Moisture        *float64
	CupScore        *float64
	Grade           string
	// Signatures are the electronic signatures behind the certificate (019),
	// printed as Part 11 §11.50 requires: name, date and time, and meaning.
	Signatures []SignatureLine
	// Template (026), when the certificate has one: the customer's layout.
	Template *CoALayout
}

// CoALayout is a customer's certificate layout with its results filled in.
type CoALayout struct {
	Title           string
	Customer        string
	HeaderNote      string
	FooterStatement string
	ShowSignatures  bool
	Rows            []CoARow
}

// CoARow is one printed result.
type CoARow struct {
	Label   string
	Result  string // "" when not tested
	Unit    string
	Spec    string // "" when not shown or no spec
	Verdict string // pass / fail / ""
}

// SignatureLine is one electronic signature as a certificate prints it.
type SignatureLine struct {
	Name     string
	Email    string
	Meaning  string
	SignedAt string
	Reason   string
	Context  string
}

func RenderCoA(d CoAData) ([]byte, error) {
	if d.Template != nil {
		return renderTemplatedCoA(d)
	}
	var buf bytes.Buffer
	return writePDF(&buf, func(pdf *gofpdf.Fpdf) {
		heading(pdf, "CERTIFICATE OF ANALYSIS")
		line(pdf, "CoA Number:", d.CoaNumber)
		line(pdf, "Export Lot:", d.LotBusinessID)
		if d.BatchBusinessID != "" {
			line(pdf, "Batch:", d.BatchBusinessID)
		}
		if d.DocumentRef != "" {
			line(pdf, "Document Ref:", d.DocumentRef)
		}
		line(pdf, "Issued By:", d.IssuedBy)
		line(pdf, "Issued At:", d.IssuedAt)
		line(pdf, "Status:", d.Status)
		pdf.Ln(4)
		pdf.SetFont("Arial", "B", 12)
		pdf.Cell(0, 8, "Lab Results Summary")
		pdf.Ln(9)
		line(pdf, "Moisture:", fmtFloat(d.Moisture, "%"))
		line(pdf, "Cup Score:", fmtFloat(d.CupScore, "pts"))
		if d.Grade != "" {
			line(pdf, "Grade:", d.Grade)
		}
		pdf.Ln(4)
		pdf.SetFont("Arial", "B", 12)
		pdf.Cell(0, 8, "Electronic Signatures")
		pdf.Ln(9)
		if len(d.Signatures) == 0 {
			line(pdf, "", "None recorded - this certificate is not electronically signed.")
		}
		signatureLines(pdf, d.Signatures)
		footer(pdf, "Generated by IAG Quality Control (CUPPA LIMS). Signatures are verified against the record as signed.")
	})
}

func signatureLines(pdf *gofpdf.Fpdf, sigs []SignatureLine) {
	for _, sig := range sigs {
		who := sig.Name
		if who == "" {
			who = sig.Email
		} else if sig.Email != "" {
			who += " <" + sig.Email + ">"
		}
		label := sig.Meaning
		if sig.Context != "" {
			label += " (" + sig.Context + ")"
		}
		line(pdf, label+":", who+" - "+sig.SignedAt)
		if sig.Reason != "" {
			line(pdf, "", "Reason: "+sig.Reason)
		}
	}
}

/*
renderTemplatedCoA prints a certificate in a customer's layout: their title
and note, a results table in their order with their labels and units, the
specification where they asked for it, and their statement. A parameter not
tested on this batch prints as "not tested" — never as a blank that could be
read as a pass.
*/
func renderTemplatedCoA(d CoAData) ([]byte, error) {
	t := d.Template
	var buf bytes.Buffer
	return writePDF(&buf, func(pdf *gofpdf.Fpdf) {
		heading(pdf, strings.ToUpper(t.Title))
		line(pdf, "CoA Number:", d.CoaNumber)
		if t.Customer != "" {
			line(pdf, "Customer:", t.Customer)
		}
		line(pdf, "Lot:", d.LotBusinessID)
		if d.BatchBusinessID != "" {
			line(pdf, "Batch:", d.BatchBusinessID)
		}
		if d.DocumentRef != "" {
			line(pdf, "Document Ref:", d.DocumentRef)
		}
		line(pdf, "Issued:", d.IssuedAt+" by "+d.IssuedBy)
		if t.HeaderNote != "" {
			pdf.Ln(2)
			pdf.SetFont("Arial", "", 10)
			pdf.MultiCell(0, 5, tr(pdf, t.HeaderNote), "", "L", false)
		}
		pdf.Ln(4)
		showSpec := false
		for _, r := range t.Rows {
			showSpec = showSpec || r.Spec != ""
		}
		widths := []float64{70, 40, 25}
		headers := []string{"Parameter", "Result", "Unit"}
		if showSpec {
			widths = []float64{55, 30, 20, 45, 24}
			headers = []string{"Parameter", "Result", "Unit", "Specification", "Verdict"}
		}
		pdf.SetFont("Arial", "B", 10)
		pdf.SetFillColor(240, 240, 240)
		for i, h := range headers {
			pdf.CellFormat(widths[i], 7, tr(pdf, h), "1", 0, "L", true, 0, "")
		}
		pdf.Ln(-1)
		pdf.SetFont("Arial", "", 10)
		for _, r := range t.Rows {
			result := r.Result
			if result == "" {
				result = "not tested"
			}
			cells := []string{r.Label, result, r.Unit}
			if showSpec {
				cells = append(cells, r.Spec, strings.ToUpper(r.Verdict))
			}
			for i, c := range cells {
				pdf.CellFormat(widths[i], 7, tr(pdf, c), "1", 0, "L", false, 0, "")
			}
			pdf.Ln(-1)
		}
		if t.ShowSignatures {
			pdf.Ln(4)
			pdf.SetFont("Arial", "B", 12)
			pdf.Cell(0, 8, "Electronic Signatures")
			pdf.Ln(9)
			if len(d.Signatures) == 0 {
				line(pdf, "", "None recorded - this certificate is not electronically signed.")
			}
			signatureLines(pdf, d.Signatures)
		}
		statement := t.FooterStatement
		if statement == "" {
			statement = "Generated by IAG Quality Control."
		}
		footer(pdf, statement)
	})
}
